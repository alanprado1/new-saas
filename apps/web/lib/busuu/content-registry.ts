const isProductionEndpoint = (renderer: string | null) => renderer === 'community_production' || renderer === 'production_choice' || renderer === 'production_choice_v1';
export function getRuntimeCompletionMetadata(spec: LessonSpec) {
  if (spec.optionalProduction) return spec.optionalProduction;
  const tail = spec.screens.at(-1);
  return spec.screens.length > 1 && tail && isProductionEndpoint(tail.rawRenderer) &&
    !spec.screens.slice(0, -1).some(s => isProductionEndpoint(s.rawRenderer))
    ? { endpointOptional: true, coreTeachingScreenCount: spec.screens.length - 1 } : null;
}
export function assertContentAlignment(pack: LessonContentPack, spec: LessonSpec) {
  if (pack.structuralContract) { assertSummaryStructure(pack, spec); return; }
  const optional = pack.completion?.optionalSurfaces ?? [];
  const metadata = getRuntimeCompletionMetadata(spec);
  const partitioned = pack.schemaVersion === '1.1' && pack.completion?.contractVersion === '1.0' &&
    metadata?.endpointOptional === true && pack.baseScreenCount === metadata.coreTeachingScreenCount &&
    pack.completion.requiredScreenIds.join('|') === pack.screens.map(s => s.screenId).join('|') && optional.length > 0;
  if (pack.recordId !== spec.recordId || pack.screens.length !== pack.baseScreenCount ||
    (optional.length ? !partitioned || pack.baseScreenCount + optional.length !== spec.baseScreenCount : pack.baseScreenCount !== spec.baseScreenCount) ||
    [...pack.screens, ...optional].map(s => s.screenId).join('|') !== spec.screens.map(s => s.screenId).join('|')) throw new Error('Content pack differs from the recorded lesson sequence');
  for (const [i, screen] of pack.screens.entries()) {
    const source = spec.screens[i];
    if (screen.sourceContract?.feedbackTranscriptResolution && !hasRetainedFeedbackOmission(screen, source)) throw new Error('Feedback omission differs from retained occurrence evidence');
    if (screen.dialogue?.kind === 'single_speaker' && (screen.sourceContract?.recordedSpeakerCount !== 1 ||
      !source.rawMediaStructure || typeof source.rawMediaStructure !== 'object' || !('speaker_count' in source.rawMediaStructure) || source.rawMediaStructure.speaker_count !== 1)) throw new Error('Single-speaker scene differs from retained speaker count');
    if (screen.sourceContract && (screen.sourceContract.sourceActivityId !== source.sourceActivityId ||
      (Object.hasOwn(screen.sourceContract, 'sourceScreenId') && screen.sourceContract.sourceScreenId !== source.sourceScreenId) ||
      screen.sourceContract.responseSlotCount !== source.rawResponseSlotCount ||
      (Object.hasOwn(screen.sourceContract, 'sourceExerciseNumber') && screen.sourceContract.sourceExerciseNumber !== source.sourceExerciseNumber))) throw new Error('Content occurrence differs from the recorded activity, exercise or response count');
  }
  for (const [i, surface] of optional.entries()) {
    const source = spec.screens[pack.screens.length + i];
    if (surface.sourceActivityId !== source.sourceActivityId || surface.sourceExerciseNumber !== source.sourceExerciseNumber ||
      !isProductionEndpoint(source.rawRenderer)) throw new Error('Optional surface differs from the recorded production endpoint');
  }
}
