const kmodel = (character, shapeNote, meaning, readings, examples) => ({
  renderer: 'kanji', prompt: `Study ${character}: shape, readings and words in context.`,
  kanji: { character, shapeNote, meaning,
    readings: readings.map(([text, note]) => ({ text, note })),
    examples: examples.map(([word, reading, meaning, sentence, sentenceReading, translation]) => ({ word, reading, meaning, sentence, sentenceReading, translation })) },
  support: { before: [jp(examples.map(e => e[3]).join(''), examples.map(e => e[4]).join('')),
    en(examples.map(e => e[5]).join(' ')),
    rule('This complete static model replaces source animation. Shape comparisons are memory aids, not stroke-order instructions or etymology.')], after: [] },
  audio: { text: examples.map(e => e[3]).join(''), reading: examples.map(e => e[4]).join('') },
});
const teachingTable = (prompt, caption, columns, rows, text, reading, english, reason) => {
  const s = table(prompt, caption, columns, rows, text, reading, reason);
  s.support.before.unshift(jp(text, reading), en(english)); return s;
};
// Source scaffolds and response readings are separate from a full source transcript.
const scaffold = s => { s.support.before.push(jp(s.scaffold.join('＿'))); return s; };
const noAudio = s => { s.audio = { text: null }; return s; };
const cueFeedback = (s, text, reading, english, reason) => {
  s.support.after = [jp(text, reading), en(english), rule(reason)]; delete s.audio.feedbackText; return s;
};

